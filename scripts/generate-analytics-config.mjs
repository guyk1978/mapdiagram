/**
 * Writes assets/analytics-config.js from environment variables (Cloudflare Pages / CI).
 * NEXT_PUBLIC_GA_ID or GA_ID — Google Analytics 4 measurement ID.
 * NEXT_PUBLIC_ADSENSE_CLIENT_ID or ADSENSE_CLIENT_ID — optional AdSense client id.
 */
import { writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const OUT = join(ROOT, "assets", "analytics-config.js");

const DEFAULT_GA_ID = "G-LDVB4978S7";

function envId(...keys) {
  for (const key of keys) {
    const v = process.env[key];
    if (v && String(v).trim()) return String(v).trim();
  }
  return null;
}

const gaMeasurementId = envId("NEXT_PUBLIC_GA_ID", "GA_ID") || DEFAULT_GA_ID;
const adsenseClientId = envId("NEXT_PUBLIC_ADSENSE_CLIENT_ID", "ADSENSE_CLIENT_ID");

const content = `/* Generated by scripts/generate-analytics-config.mjs — do not edit manually */
window.__MD_ANALYTICS_CONFIG__ = Object.freeze({
  gaMeasurementId: ${JSON.stringify(gaMeasurementId)},
  adsenseClientId: ${JSON.stringify(adsenseClientId)},
});
`;

writeFileSync(OUT, content, "utf8");
console.log("[generate-analytics-config] wrote assets/analytics-config.js");
